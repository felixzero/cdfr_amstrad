.globl _blit_sprite_xor
.globl _swap_buffers
.globl _wait_for_vsync

.area _CODE

RECT_X = 0
RECT_Y = 1
RECT_W = 2
RECT_H = 3


_wait_for_vsync:
    ld b, #0xF5
wait_loop:
    in a, (c)
    rra
    jr NC, wait_loop
    ret


_swap_buffers:
    ; Set screen high address
    ld bc, #0xBC0C
    out (c), c
    ld a, (#current_buffer)
    xor a, #0x20
    ld (#current_buffer), a
    inc b
    out (c), a

    ret


; void blit_sprite_xor(const uint8_t *sprite, const struct rect *position);
; arg: HL = sprite, DE = position
_blit_sprite_xor:
    push de
    pop iy

    ld b, RECT_H(iy)
.loop_lines:
    ld a, RECT_Y(iy)
    add b
    call address_of_position

    ; Copy line
    ld c, RECT_W(iy)
    sra c
    xor a
.loop_columns:
    ld a, (de)
    xor a, (hl)
    ld (de), a
    inc hl
    inc de
    dec c
    jr NZ, .loop_columns

    dec b
    jr NZ, .loop_lines

    ret


; In : Y in A
; Ret: DE = address
address_of_position:
    push hl

    ; Read high byte
    ld h, #(screen_lookup_table_h >> 8)
    ld l, a
    ld d, (hl)
    ld a, (#current_buffer)
    bit 5, a
    jr NZ, skip
    set 7, d
skip:

    ; Read low byte
    ld h, #(screen_lookup_table_l >> 8)
    srl l
    srl l
    srl l
    ld a, RECT_X(iy)
    srl a
    add a, (hl)
    jr NC, skip_carry
    inc d
skip_carry:
    ld e, a

    pop hl
    ret

